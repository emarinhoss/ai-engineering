"""Task 9: tables and figures from the committed analysis outputs (nothing is recomputed here).

Reads runs/pool3r/analysis/replay_s*.csv, mf.csv, feasibility.json, inverse/result.json and writes
  docs/validation/2026-11-04_task9_tables.md       median [25th, 75th percentile] over the 10 seeds
  docs/validation/2026-11-04_task9_replay.png      replay error and hypervolume regret against n
  docs/validation/2026-11-04_task9_mf.png          single vs two-level held-out error against n

    python -m analysis.task9_report
"""
import csv
import glob
import json
from pathlib import Path

import numpy as np

from postprocess import plot_replay
from postprocess.plot_replay import plt

A = Path("runs/pool3r/analysis")
OUT = Path("docs/validation")
STRATEGIES = ("random", "lhs", "al_maxvar", "al_ehvi", "al_ehvi_feas")
plot_replay.COLOURS["al_ehvi_feas"] = "#009E73"
MF_COLOURS = {"single": "#888888", "two": "#0072B2"}


def load(paths, key):
    """data[key value][metric][n] = values over seeds."""
    data = {}
    for p in paths:
        with open(p, newline="") as f:
            for r in csv.DictReader(f):
                data.setdefault(r[key], {}).setdefault(r["metric"], {}).setdefault(int(r["n"]), []).append(float(r["value"]))
    return data


def cell(v, fmt):
    q25, med, q75 = np.percentile(v, [25, 50, 75])
    return f"{med:{fmt}} [{q25:{fmt}}, {q75:{fmt}}]"


def table(data, rows, metric, fmt):
    ns = sorted(next(iter(data[rows[0]].values())).keys())
    lines = ["| n | " + " | ".join(rows) + " |", "|---" * (len(rows) + 1) + "|"]
    for n in ns:
        lines.append(f"| {n} | " + " | ".join(cell(data[r][metric][n], fmt) if n in data[r].get(metric, {}) else "-"
                                              for r in rows) + " |")
    return "\n".join(lines)


def plot_mf(mf, lf_raw, path):
    fig, axes = plt.subplots(1, 2, figsize=(10, 4.2))
    for ax, (metric, label) in zip(axes, (("rmse_recovery", "RMSE recovery_total [-]"),
                                          ("rmse_q_rel", "relative RMSE q_peak [-]"))):
        for model in ("single", "two"):
            ns = sorted(mf[model][metric])
            q25, med, q75 = np.array([np.percentile(mf[model][metric][n], [25, 50, 75]) for n in ns]).T
            ax.plot(ns, med, marker="o", color=MF_COLOURS[model],
                    label={"single": "NS only (GP)", "two": "Euler/Eckert + NS (two-level GP)"}[model])
            ax.fill_between(ns, q25, q75, color=MF_COLOURS[model], alpha=0.2, linewidth=0)
        ax.axhline(lf_raw[metric], color="k", ls="--", lw=1, label="raw low-fidelity value (no NS run)")
        ax.set(xlabel="number of NS runs", ylabel=label, yscale="log")
    axes[0].legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)


def main():
    replay = load(sorted(glob.glob(str(A / "replay_s*.csv"))), "strategy")
    mf = load([A / "mf.csv"], "model")
    lf_raw = {m: v[0][0] for m, v in mf.pop("lf_raw").items()}
    feas = json.loads((A / "feasibility.json").read_text())
    inv = json.loads((A / "inverse" / "result.json").read_text())
    n_seeds = len(replay["random"]["rmse_recovery"][96])

    plot_replay.plot_error(replay, STRATEGIES, OUT / "2026-11-04_task9_replay.png")
    plot_mf(mf, lf_raw, OUT / "2026-11-04_task9_mf.png")

    md = ["# Task 9 analysis tables (generated by `python -m analysis.task9_report`)", "",
          f"Median [25th, 75th percentile] over {n_seeds} seeds. Sources: `runs/pool3r/analysis/`. "
          "Pool: `runs/pool3r/pool3r_table.csv` (159 NS points, 152 converged; 316 Euler runs).", "",
          "## 1. Replay (n = NS runs spent, failed picks included)", ""]
    for metric, fmt in (("rmse_recovery", ".4f"), ("rmse_q_rel", ".4f"), ("hv_regret", ".3f"),
                        ("n_failed", ".1f"), ("cov90_recovery", ".2f"), ("cov90_q", ".2f")):
        md += [f"### {metric}", "", table(replay, STRATEGIES, metric, fmt), ""]
    md += ["## 2. Two-level (Euler + Eckert, then NS) against NS only", "",
           f"Raw low-fidelity value as the prediction (no NS run): RMSE recovery {lf_raw['rmse_recovery']:.4f}, "
           f"relative RMSE q_peak {lf_raw['rmse_q_rel']:.3f}.", ""]
    for metric, fmt in (("rmse_recovery", ".4f"), ("rmse_q_rel", ".4f"), ("cov90_recovery", ".2f"),
                        ("cov90_q", ".2f")):
        md += [f"### {metric}", "", table(mf, ("single", "two"), metric, fmt), ""]
    for metric in ("rho_recovery", "rho_q"):
        md += [f"### {metric} (two-level)", "", table(mf, ("two",), metric, ".3f"), ""]
    md += ["## 3. Feasibility classifier (5-fold stratified CV)", "",
           f"- points {feas['n']}, failed {feas['n_failed']}",
           f"- accuracy at p = 0.5: {feas['accuracy_at_0.5']:.3f}; always-converges baseline: "
           f"{feas['baseline_accuracy_always_converges']:.3f}; rank AUC {feas['rank_auc']:.2f}",
           *[f"- threshold {t}: failed runs skipped {feas[f'at_{t}']['failed_skipped']}, good runs lost "
             f"{feas[f'at_{t}']['good_lost']}" for t in (0.5, 0.9)], "",
           "| failed case | mach | total turning [deg] | out-of-fold p |", "|---|---|---|---|",
           *[f"| {p['case_id']} | {p['mach']:.2f} | {p['theta_total_deg']:.1f} | {p['p_oof']:.3f} |"
             for p in feas["failed_points"]], "",
           "## 4. Robust inverse query", "",
           f"- cap {inv['q_cap_W_m2']:.0f} W/m2 ({inv['cap_rule']}); required probability {inv['prob_required']}",
           f"- feasible: {inv['feasible']}; candidates {inv['n_candidates']}; envelope points {inv['n_envelope_points']}"]
    if not inv["feasible"]:
        md += [f"- best minimum probability over the envelope: {inv['best_min_probability']:.1e}",
               f"- envelope points where some candidate meets the probability: "
               f"{inv['n_envelope_points_some_candidate_meets_prob']} of {inv['n_envelope_points']}", "",
               "Envelope points where no candidate meets it (lowest predicted q median over the candidates):", "",
               "| mach | altitude [km] | T_wall [K] | best probability | lowest q median [W/m2] |", "|---|---|---|---|---|",
               *[f"| {p['mach']:.2f} | {p['altitude_km']:.2f} | {p['T_wall_K']:.0f} | "
                 f"{p['best_probability_over_candidates']:.2f} | {p['lowest_predicted_q_median_W_m2']:.0f} |"
                 for p in inv["per_envelope_point"] if p["best_probability_over_candidates"] < inv["prob_required"]]]
    (OUT / "2026-11-04_task9_tables.md").write_text("\n".join(md) + "\n")
    print("wrote", OUT / "2026-11-04_task9_tables.md")


if __name__ == "__main__":
    main()

def read_outline():
    """[{number, title, start, minutes, main, message, body, notes}] in outline order. The presenter
    notes run over several lines: each indented line after the field is one more paragraph."""
    slides, cur, main = [], None, True
    for line in OUTLINE.read_text(encoding="utf-8").splitlines():
        head = SLIDE_HEAD.match(line)
        if head:
            cur = {"number": int(head.group(1)), "title": head.group(2), "main": main,
                   "start": head.group(3),
                   "minutes": float(head.group(4)) if head.group(4) else None,
                   "message": "", "body": "", "notes": ""}
            slides.append(cur)
        elif line.startswith("## "):
            cur = None
            main = main and not line.startswith("## Backup")
        elif cur is not None:
            for key, tag in FIELDS:
                if line.startswith(f"- **{tag}:** "):
                    cur[key] = line[len(f"- **{tag}:** "):].strip()
            if line.startswith("  ") and line.strip() and cur["notes"]:
                cur["notes"] += "\n" + line.strip()
    return slides


def write_transcript(slides, v, path=TRANSCRIPT):
    """The presenter notes of every slide, filled from the records, as one Markdown file."""
    main = [s for s in slides if s["main"]]
    out = ["# Transcript: the drone deck, version 3", "",
           ("This file is the presenter notes of version 3 of the drone deck, slide by slide. The deck "
            "build writes it from the outline, and fills each number from the records. The text uses "
            "ASD-STE100 Simplified Technical English. Do not edit this file: edit the outline and build "
            "the deck again."), ""]
    for s in slides:
        if s["number"] == len(main) + 2:
            out += ["## Slide " + str(len(main) + 1) + ": Backup", "",
                    "These are the backup slides. I open one only when a question needs it.", ""]
        out.append(f"## Slide {s['number']}: {s['title']}")
        if s["start"]:
            out += ["", f"*{s['start']}" + (f", {s['minutes']:g} min*" if s["minutes"] else " onward*")]
        for para in v2.fill(s["notes"], v).split("\n"):
            out += ["", para]
        out.append("")
    Path(path).write_text("\n".join(out))



from prelim import p3_loft as p3

FIGURE_LABEL = p3.RENDER_LABEL


def load(out):
    return json.loads((Path(out) / "p3.json").read_text())


def write_figures(out, folder):
    """Three orthographic views and one perspective view from the exported STL, and the arrangement drawing,
    each with a sidecar record <name>.json."""
    from geometry3d import aircraft as ac
    from geometry3d import mesh, render
    out, folder = Path(out), Path(folder)
    folder.mkdir(parents=True, exist_ok=True)
    res = load(out)
    parts = mesh.read_stl(out / "loft.stl")
    side = {"label": FIGURE_LABEL, "made_by": "prelim/p3_report.py (geometry3d/render.py), matplotlib only",
            "record": str((out / "p3.json").relative_to(p3.REPO)), "p3_json_sha256": p3.sha256(out / "p3.json"),
            "stl_sha256": p3.sha256(out / "loft.stl"), "record_commit": res["inputs"]["commit"], "units": "ft"}
    for name in render.VIEWS:
        render.view(parts, name, folder / f"{name}.png", "Task 12 r0 loft: " + FIGURE_LABEL, res["loft"]["propeller"])
        (folder / f"{name}.json").write_text(json.dumps(dict(side, figure=f"{name}.png", view=render.VIEWS[name][3],
                                                             projection=render.VIEWS[name][2]), indent=1))
    d, L, A = p3.inputs()
    f = ac.build(d, L, A)["fuselage"]
    x = np.linspace(1e-6, f.length, 600)
    half, top, bottom, _ = f.lines(x)
    s = res["loft"]["surfaces"]["wing"]
    render.arrangement((x, half, top, bottom), res["gates"]["4"]["boxes"], (s["x_le"], s["c_root"], s["z0"]),
                       folder / "arrangement.png", "Task 12 r0 loft: " + FIGURE_LABEL)
    (folder / "arrangement.json").write_text(json.dumps(dict(side, figure="arrangement.png", view="side and top, boxes of gate 4"), indent=1))


def pct(v, n=1):
    return "-" if v is None else f"{100 * v:+.{n}f} %"


def num(v, n=2):
    return "-" if v is None else f"{v:,.{n}f}"



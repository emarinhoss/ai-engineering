def load(out):
    return json.loads((Path(out) / "p8.json").read_text())


def f(v, n=1):
    return "-" if v is None else f"{v:,.{n}f}"


def headline(row):
    x = next(x for x in row["numbers"] if x["name"] == row["headline"])
    return f"{p8.fmt(x)} {x['unit']}".replace(" -", "")



def doc_checks(out):
    """Acceptance on the generated requirement: its first lines state PD-11, and every number of each row is printed in
    that row's line of the table."""
    r = load(out)
    text = requirement_text(out)
    head = "\n".join(text.splitlines()[:4])
    first = "does not design (PD-11)" in head
    table = {ln.split("|")[1].strip(): ln for ln in text.splitlines() if ln.startswith("| EP-") and ln.count("|") == 5}
    missing = [f"{row['id']} {x['name']}" for row in r["rows"] for x in row["numbers"] if p8.fmt(x) not in table.get(row["id"], "")]
    return {"pd11_in_first_lines": first, "numbers_missing_from_table": missing,
            "verdict": "pass" if first and not missing and len(table) == 9 else "fail"}



def _load(folder):
    return {name: json.loads((folder / f"{name}.json").read_text())
            for name in ("design_pusher", "robust_candidate", "info_gap", "cell_result")}


def _ft(x):
    return f"{x:,.1f}"


def _verdict(row):
    return f"**{row['verdict']}**"


def key_rows(p, new, old):
    """(label, Gate B value, r0 value, format) for the side-by-side table; values straight from the records."""
    hz = p["info_gap"]["horizons"]
    d0, d1 = old["design_pusher"], new["design_pusher"]
    rows = [("take-off weight W0 (lb)", d0["W0_lb"], d1["W0_lb"], ",.3f"),
            ("mission fuel (lb)", d0["fuel_lb"], d1["fuel_lb"], ",.3f"),
            ("empty weight (lb)", d0["We_lb"], d1["We_lb"], ",.3f"),
            ("L_sized (h)", old["robust_candidate"]["L_sized_h"], new["robust_candidate"]["L_sized_h"], ".3f"),
            ("span (ft)", d0["wing"]["span"], d1["wing"]["span"], ".3f"),
            ("service ceiling, Stage 1 (ft)", d0["performance"]["service_ceiling_ft"], d1["performance"]["service_ceiling_ft"], ",.1f"),
            ("power margin", p["power_margin"]["gate_b_row"], p["power_margin"]["r0"], ".4f"),
            ("take-off over 50 ft (ft)", d0["performance"]["takeoff_ft"], d1["performance"]["takeoff_ft"], ",.1f"),
            ("landing over 50 ft (ft)", d0["performance"]["landing_ft"], d1["performance"]["landing_ft"], ",.1f"),
            ("share of mission fuel burned in unchoked table cells", d0["unchoked_fuel_share"], d1["unchoked_fuel_share"], ".4f")]
    for key, label in (("R5_guarantee", "R5 guarantee horizon (3.5 h on station)"),
                       ("mode_endurance", "endurance mode horizon"), ("mode_cliff", "cliff mode horizon"),
                       ("R7", "R7 horizon (smaller of take-off and landing)"), ("TO", "take-off horizon"),
                       ("LD", "landing horizon"), ("R5", "nominal 8 h horizon (R5)"),
                       ("R5_reserve_usable", "8 h horizon with the reserve usable")):
        rows.append((label, hz[key]["gate_b"], hz[key]["r0"], ".4f"))
    return rows



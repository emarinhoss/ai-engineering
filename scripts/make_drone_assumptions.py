"""Render docs/drone_assumptions.md from data/drone/*.yaml.

Usage:
  python scripts/make_drone_assumptions.py          write the document
  python scripts/make_drone_assumptions.py --check  exit 1 if the committed document differs byte
                                                    for byte from the rendered text, else 0
"""

from __future__ import annotations

import argparse
import difflib
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT))

from drone import ledger

OUT_PATH = REPO_ROOT / "docs" / "drone_assumptions.md"
HEADINGS = {
    "air": "Air (ISA, sea level)",
    "battery": "Battery",
    "propulsion": "Propulsion",
    "structure": "Structure",
    "rules": "Rules, fixed design choices and fidelity constants",
}


def _cell(text: str) -> str:
    """One table cell: pipes escaped, no line breaks."""
    return str(text).replace("|", "\\|").replace("\n", " ")


def _band(band) -> str:
    if band is None:
        return "-"
    return f"[{band[0]!r}, {band[1]!r}]"


def render() -> str:
    lines = [
        "# Drone data ledger",
        "",
        "Generated by `scripts/make_drone_assumptions.py` from `data/drone/*.yaml`. Do not edit by hand.",
        "A quantity graded `assumed` carries a band; a band is the range the study will sweep, not a",
        "claim about the value. Validation data are in `data/validation/` and are not listed here.",
        "",
    ]
    for set_name in ledger.SET_NAMES:
        lines += [
            f"## {HEADINGS[set_name]}",
            "",
            f"File: `data/drone/{set_name}.yaml`",
            "",
            "| Name | Value | Units | Confidence | Band | Source |",
            "|---|---|---|---|---|---|",
        ]
        quantities = ledger._read(set_name)
        for key, q in quantities.items():
            lines.append(
                f"| {_cell(key)} | {q.value!r} | {_cell(q.units)} | {q.confidence} "
                f"| {_band(q.band)} | {_cell(q.source)} |"
            )
        lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="compare with the committed document instead of writing it",
    )
    args = parser.parse_args(argv)
    rendered = render().encode("utf-8")

    if args.check:
        committed = OUT_PATH.read_bytes() if OUT_PATH.exists() else b""
        if committed == rendered:
            return 0
        diff = difflib.unified_diff(
            committed.decode("utf-8", "replace").splitlines(keepends=True),
            rendered.decode("utf-8").splitlines(keepends=True),
            fromfile=str(OUT_PATH),
            tofile="rendered",
        )
        sys.stdout.writelines(list(diff)[:200])
        print(f"\n{OUT_PATH} is stale. Regenerate with: python scripts/make_drone_assumptions.py")
        return 1

    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_bytes(rendered)
    print(f"wrote {OUT_PATH}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
